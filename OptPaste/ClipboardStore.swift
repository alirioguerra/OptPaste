import AppKit
import CryptoKit
import Observation

/// Watches the general pasteboard and keeps a persisted history of what was copied.
///
/// macOS has no public "clipboard history" API, so this polls `changeCount` (cheap and
/// prompt-free) and only reads the pasteboard contents when something new was copied.
@Observable
final class ClipboardStore {
    private(set) var items: [ClipboardItem] = []

    @ObservationIgnored private let settings: AppSettings
    @ObservationIgnored private var lastChangeCount: Int
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private let directory: URL
    @ObservationIgnored private let imagesDirectory: URL
    @ObservationIgnored private let thumbnails = NSCache<NSUUID, NSImage>()

    /// Markers apps add to pasteboard writes (see nspasteboard.org). Concealed is what
    /// password managers use; transient and auto-generated content was not copied by the user.
    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    private static let maxRTFSize = 1_000_000

    init(settings: AppSettings) {
        self.settings = settings
        lastChangeCount = NSPasteboard.general.changeCount
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        directory = support.appendingPathComponent("OptPaste", isDirectory: true)
        imagesDirectory = directory.appendingPathComponent("images", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDirectory, withIntermediateDirectories: true)
        load()
    }

    /// Pinned entries first, then the rest from newest to oldest.
    var displayItems: [ClipboardItem] {
        items.filter(\.isPinned) + items.filter { !$0.isPinned }
    }

    func startMonitoring() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.1
    }

    // MARK: - Actions

    func copyToPasteboard(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
            if let rtf = item.rtf {
                pasteboard.setData(rtf, forType: .rtf)
            }
        case .image:
            if let data = try? Data(contentsOf: imageURL(for: item)) {
                pasteboard.setData(data, forType: .png)
                if let tiff = NSImage(data: data)?.tiffRepresentation {
                    pasteboard.setData(tiff, forType: .tiff)
                }
            }
        case .files:
            pasteboard.writeObjects((item.fileURLs ?? []) as [NSURL])
        }
        lastChangeCount = pasteboard.changeCount

        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        trim()
        save()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        deleteImage(of: item)
        save()
    }

    /// Clears the history, keeping pinned entries (same as Windows).
    func clear() {
        items.filter { !$0.isPinned }.forEach(deleteImage(of:))
        items.removeAll { !$0.isPinned }
        save()
    }

    func trim() {
        var unpinned = 0
        items.removeAll { item in
            guard !item.isPinned else { return false }
            unpinned += 1
            if unpinned > settings.historyLimit {
                deleteImage(of: item)
                return true
            }
            return false
        }
    }

    func thumbnail(for item: ClipboardItem) -> NSImage? {
        let key = item.id as NSUUID
        if let cached = thumbnails.object(forKey: key) { return cached }
        guard let image = NSImage(contentsOf: imageURL(for: item)) else { return nil }
        thumbnails.setObject(image, forKey: key)
        return image
    }

    // MARK: - Capture

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard var item = capture(from: pasteboard) else { return }

        if let existing = items.firstIndex(where: { $0.signature == item.signature }) {
            let old = items.remove(at: existing)
            item.isPinned = old.isPinned
            if item.kind == .image {
                item.id = old.id // reuse the image already on disk
            }
        }
        items.insert(item, at: 0)
        trim()
        save()
    }

    private func capture(from pasteboard: NSPasteboard) -> ClipboardItem? {
        let types = Set(pasteboard.types ?? [])
        guard !types.isEmpty, types.isDisjoint(with: Self.ignoredTypes) else { return nil }
        if !settings.savePasswords && types.contains(Self.concealedType) { return nil }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return ClipboardItem(kind: .files, fileURLs: urls,
                                 signature: "files:" + urls.map(\.path).joined(separator: "\n"),
                                 sourceBundleID: source)
        }

        let string = pasteboard.string(forType: .string)
        let hasImage = types.contains(.png) || types.contains(.tiff)
        // Rich text from apps like Pages or Excel often carries an image rendition too;
        // treat it as text. Pure image copies (screenshots, "Copy Image") have no RTF.
        if hasImage, string == nil || !types.contains(.rtf), let png = pngData(from: pasteboard) {
            var item = ClipboardItem(kind: .image, signature: "image:" + Self.hash(png), sourceBundleID: source)
            if let existing = items.first(where: { $0.signature == item.signature }) {
                item.id = existing.id
            } else {
                try? png.write(to: imageURL(for: item))
            }
            return item
        }

        if let string, !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let rtf = pasteboard.data(forType: .rtf).flatMap { $0.count <= Self.maxRTFSize ? $0 : nil }
            return ClipboardItem(kind: .text, text: string, rtf: rtf,
                                 signature: "text:" + Self.hash(Data(string.utf8)),
                                 sourceBundleID: source)
        }
        return nil
    }

    private func pngData(from pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff) else { return nil }
        return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    // MARK: - Persistence

    private var historyURL: URL { directory.appendingPathComponent("history.json") }

    private func imageURL(for item: ClipboardItem) -> URL {
        imagesDirectory.appendingPathComponent(item.id.uuidString).appendingPathExtension("png")
    }

    private func deleteImage(of item: ClipboardItem) {
        guard item.kind == .image else { return }
        thumbnails.removeObject(forKey: item.id as NSUUID)
        try? FileManager.default.removeItem(at: imageURL(for: item))
    }

    private func load() {
        guard let data = try? Data(contentsOf: historyURL),
              let decoded = try? JSONDecoder().decode([ClipboardItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: historyURL, options: .atomic)
    }
}
